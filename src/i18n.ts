/**
 * UI strings. Keys are the Chinese source text; `t()` returns the English
 * translation when the locale is `en`, otherwise the key itself. `{0}`, `{1}`…
 * are positional placeholders.
 *
 * Locale: the plugin setting `language` ('auto' | 'zh' | 'en'); `auto` follows
 * Obsidian's own language (localStorage `language`, absent = English).
 */
export type Locale = 'zh' | 'en';
export function detectLocale(): Locale {
  if (typeof window === 'undefined') return 'zh'; // tests
  try {
    const l = window.localStorage.getItem('language');
    return !l || l.startsWith('zh') ? (l ? 'zh' : 'en') : 'en';
  } catch { return 'en'; }
}
let locale: Locale = detectLocale();
export function setLocale(pref: 'auto' | Locale): void { locale = pref === 'auto' ? detectLocale() : pref; }
export function getLocale(): Locale { return locale; }

export function t(key: string, args?: unknown[]): string {
  const s = (locale === 'en' ? EN[key] : undefined) ?? key;
  return args ? s.replace(/\{(\d+)\}/g, (_m, i) => String(args[Number(i)] ?? '')) : s;
}

/** Roster status values are data ('在线' etc.); this is only for display */
export function statusLabel(status: string): string {
  return t(status);
}

